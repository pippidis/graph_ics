"""The small drawing contract used by geometry, without a runtime Cairo import."""

from __future__ import annotations

from typing import TYPE_CHECKING, Protocol, cast

if TYPE_CHECKING:
    from cairo import LineCap, LineJoin, Path

# Cairo's enum uses integer zero for butt caps; keep imports optional at runtime.
BUTT_CAP = cast('LineCap', 0)
ROUND_JOIN = cast('LineJoin', 1)


class DrawingContext(Protocol):
    def save(self) -> None: ...
    def restore(self) -> None: ...
    def translate(self, tx: float, ty: float) -> None: ...
    def append_path(self, path: Path) -> None: ...
    def fill(self) -> None: ...
    def close_path(self) -> None: ...
    def set_line_join(self, line_join: LineJoin) -> None: ...
    def new_path(self) -> None: ...
    def arc(self, xc: float, yc: float, radius: float, angle1: float, angle2: float) -> None: ...
    def move_to(self, x: float, y: float) -> None: ...
    def line_to(self, x: float, y: float) -> None: ...
    def set_source_rgba(self, red: float, green: float, blue: float, alpha: float = 1) -> None: ...
    def set_line_width(self, width: float) -> None: ...
    def set_line_cap(self, line_cap: LineCap) -> None: ...
    def stroke(self) -> None: ...
